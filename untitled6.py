def generate_text(
    prompt,
    system_instruction="You are CareerPilot AI, a helpful career assistant.",
    max_new_tokens=250,
    temperature=0.3
):
    """Generate a response using the local instruction-tuned LLM."""

    messages = [
        {"role": "system", "content": system_instruction},
        {"role": "user", "content": prompt}
    ]

    inputs = tokenizer.apply_chat_template(
        messages,
        tokenize=True,
        add_generation_prompt=True,
        return_tensors="pt",
        return_dict=True
    )

    inputs = {k: v.to(DEVICE) for k, v in inputs.items()}

    kwargs = {
        "max_new_tokens": max_new_tokens,
        "pad_token_id": tokenizer.eos_token_id,
        "do_sample": temperature > 0
    }

    if temperature > 0:
        kwargs.update(temperature=temperature, top_p=0.9)

    start = time.perf_counter()

    with torch.inference_mode():
        outputs = model.generate(**inputs, **kwargs)

    elapsed = time.perf_counter() - start

    new_tokens = outputs[0, inputs["input_ids"].shape[1]:]
    answer = tokenizer.decode(
        new_tokens, skip_special_tokens=True
    ).strip()

    return {
        "text": answer,
        "latency_seconds": round(elapsed, 3),
        "input_tokens": int(inputs["input_ids"].shape[1]),
        "output_tokens": int(len(new_tokens))
    }


