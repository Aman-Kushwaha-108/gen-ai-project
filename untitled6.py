def route_task(user_message):
    """Choose an allowed workflow using explicit routing rules."""
    text = user_message.strip()
    lower = text.lower()

    # Calculator
    match = re.search(
        r"(?:calculate|compute)\s+([0-9+\-*/().%\s]+)",
        text,
        flags=re.IGNORECASE
    )
    if match:
        return {
            "action": "calculator",
            "arguments": {"expression": match.group(1).strip()}
        }

    # Study plan
    if "study plan" in lower or "learning plan" in lower:
        match_days = re.search(r"\b(\d{1,2})\s+days?\b", lower)
        days = int(match_days.group(1)) if match_days else 7

        return {
            "action": "study_plan",
            "arguments": {
                "goal": text,
                "days": days
            }
        }

    # Resume/job description matching
    if "match resume" in lower or "match my skills" in lower:
        parts = re.split(r"\bjob description:\s*", text, maxsplit=1, flags=re.I)
        if len(parts) == 2:
            resume_part = re.sub(
                r"^.*?resume:\s*", "", parts[0], flags=re.I | re.S
            ).strip()

            return {
                "action": "skill_match",
                "arguments": {
                    "resume_text": resume_part,
                    "job_description": parts[1].strip()
                }
            }

    # RAG document question answering
    if document_embeddings is not None and any(
        phrase in lower
        for phrase in [
            "according to my document",
            "according to the pdf",
            "in the uploaded",
            "from my document",
            "from the pdf",
            "based on the document"
        ]
    ):
        return {"action": "rag", "arguments": {"question": text}}

    return {"action": "llm", "arguments": {"question": text}}


def run_agent(user_message, custom_instructions=""):
    """Run one controlled agent workflow and record its action trace."""
    start = time.perf_counter()

    decision = route_task(user_message)
    trace = [{
        "stage": "understand_and_decide",
        "action": decision["action"]
    }]

    try:
        action = decision["action"]
        args = decision["arguments"]

        if action in TOOLS:
            # Explicit allowlist: no arbitrary tool names or code execution.
            tool_result = TOOLS[action](**args)
            trace.append({
                "stage": "tool_execution",
                "tool": action,
                "result": tool_result
            })

            prompt = f"""
User request: {user_message}
Tool result: {json.dumps(tool_result, ensure_ascii=False)}

Explain the result clearly.
Do not claim more than the tool result supports.
"""

            answer = generate_text(
                prompt,
                system_instruction=(
                    "You are CareerPilot AI. Explain tool results honestly."
                    + ("\nCustom instructions: " + custom_instructions
                       if custom_instructions.strip() else "")
                ),
                max_new_tokens=240
            )

        elif action == "rag":
            rag_result = answer_from_documents(args["question"])
            answer = rag_result["answer"]

            trace.append({
                "stage": "retrieval",
                "sources": rag_result["sources"]
            })

        else:
            history_text = "\n".join(
                f"{item['role']}: {item['content']}"
                for item in agent_memory[-6:]
            )

            prompt = f"""
Recent conversation:
{history_text or "No previous messages."}

User request:
{user_message}

Respond helpfully and accurately. Use concise headings when useful.
If you need current facts, clearly say that they require verification.
"""

            answer = generate_text(
                prompt,
                system_instruction=(
                    "You are CareerPilot AI, a career, study, and coding assistant."
                    + ("\nCustom instructions: " + custom_instructions
                       if custom_instructions.strip() else "")
                ),
                max_new_tokens=300
            )

        agent_memory.extend([
            {"role": "user", "content": user_message},
            {"role": "assistant", "content": answer}
        ])

        # Bound memory growth for this prototype.
        del agent_memory[:-20]

        elapsed = round(time.perf_counter() - start, 3)

        evaluation_records.append({
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "action": action,
            "latency_seconds": elapsed,
            "success": True
        })

        return {
            "answer": answer,
            "action": action,
            "trace": trace,
            "latency_seconds": elapsed
        }

    except Exception as error:
        elapsed = round(time.perf_counter() - start, 3)

        evaluation_records.append({
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "action": decision["action"],
            "latency_seconds": elapsed,
            "success": False
        })

        return {
            "answer": (
                f"The requested workflow failed: {type(error).__name__}: "
                f"{error}. Please check your input and try again."
            ),
            "action": decision["action"],
            "trace": trace,
            "latency_seconds": elapsed
        }


