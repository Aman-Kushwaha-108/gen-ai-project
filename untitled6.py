def upload_and_index(files):
    if not files:
        return "Upload one or more PDF/TXT files first."

    if isinstance(files, str):
        files = [files]

    return index_documents(files)


def chat_callback(message, history, instructions, use_documents):
    message = (message or "").strip()

    if not message:
        return history, ""

    if use_documents:
        if document_embeddings is None:
            answer = (
                "Please upload and index documents first, or turn off "
                "'Answer using uploaded documents'."
            )
            history = list(history or [])
            history.extend([
                {"role": "user", "content": message},
                {"role": "assistant", "content": answer}
            ])
            return history, ""

        message = "According to my document: " + message

    result = run_agent(
        message,
        custom_instructions=instructions or ""
    )

    answer = result["answer"]

    # Display which workflow ran and its latency.
    answer += (
        f"\n\n---\n"
        f"**Agent action:** `{result['action']}`  \n"
        f"**Latency:** {result['latency_seconds']} seconds"
    )

    history = list(history or [])
    history.extend([
        {"role": "user", "content": message},
        {"role": "assistant", "content": answer}
    ])

    return history, ""


