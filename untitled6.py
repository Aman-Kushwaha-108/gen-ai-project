def safe_calculate(expression):
    """Evaluate simple arithmetic without eval() or arbitrary code."""
    if len(expression) > 100:
        raise ValueError("Expression is too long.")

    allowed = {
        ast.Add: operator.add,
        ast.Sub: operator.sub,
        ast.Mult: operator.mul,
        ast.Div: operator.truediv,
        ast.Mod: operator.mod,
        ast.Pow: operator.pow,
        ast.USub: operator.neg,
        ast.UAdd: operator.pos
    }

    tree = ast.parse(expression, mode="eval")

    def visit(node, depth=0):
        if depth > 15:
            raise ValueError("Expression is too complex.")

        if isinstance(node, ast.Expression):
            value = visit(node.body, depth + 1)

        elif isinstance(node, ast.Constant) and type(node.value) in (int, float):
            value = node.value

        elif isinstance(node, ast.BinOp) and type(node.op) in allowed:
            left = visit(node.left, depth + 1)
            right = visit(node.right, depth + 1)

            if isinstance(node.op, ast.Pow) and abs(right) > 10:
                raise ValueError("Exponent is too large.")

            value = allowed[type(node.op)](left, right)

        elif isinstance(node, ast.UnaryOp) and type(node.op) in allowed:
            value = allowed[type(node.op)](
                visit(node.operand, depth + 1)
            )

        else:
            raise ValueError("Unsupported expression.")

        if not isinstance(value, (int, float)) or not math.isfinite(value):
            raise ValueError("Invalid numeric result.")

        if abs(value) > 1e100:
            raise ValueError("Result is too large.")

        return value

    return visit(tree)


def calculator_tool(expression):
    return {"expression": expression, "result": safe_calculate(expression)}


def skill_match_tool(resume_text, job_description):
    """Simple transparent keyword overlap, not an ATS score."""
    def words(text):
        return set(re.findall(r"\b[a-zA-Z][a-zA-Z+#.]{1,}\b", text.lower()))

    resume_words = words(resume_text)
    job_words = words(job_description)

    ignored = {
        "and", "the", "with", "for", "from", "you", "your", "are",
        "our", "will", "this", "that", "have", "has", "using",
        "work", "role", "job", "skills", "ability", "strong"
    }

    job_keywords = job_words - ignored
    matched = sorted(resume_words & job_keywords)
    missing = sorted(job_keywords - resume_words)

    score = (
        round(100 * len(matched) / len(job_keywords), 1)
        if job_keywords else 0
    )

    return {
        "keyword_overlap_percentage": score,
        "matched_keywords": matched[:30],
        "potentially_missing_keywords": missing[:30],
        "limitation": (
            "This is a basic keyword-overlap measure, not an actual ATS "
            "score or a reliable measure of candidate suitability."
        )
    }


def study_plan_tool(goal, days=7):
    """Create a basic study schedule template."""
    days = max(1, min(int(days), 30))

    return {
        "goal": goal,
        "days": days,
        "plan": [
            {
                "day": day,
                "task": (
                    f"Day {day}: Study {goal}, practise one related task, "
                    "and review what you learned."
                )
            }
            for day in range(1, days + 1)
        ]
    }


