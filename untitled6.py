def split_into_chunks(text, chunk_size=180, overlap=35):
    """Split text into overlapping word-based chunks."""
    words = text.split()

    if not words:
        return []

    chunks = []
    step = max(1, chunk_size - overlap)

    for start in range(0, len(words), step):
        chunk = " ".join(words[start:start + chunk_size])

        if chunk.strip():
            chunks.append(chunk)

        if start + chunk_size >= len(words):
            break

    return chunks


def read_document(file_path):
    """Read PDF or text documents."""
    path = Path(file_path)

    if path.suffix.lower() == ".pdf":
        reader = PdfReader(str(path))
        return "\n".join(
            page.extract_text() or ""
            for page in reader.pages
        )

    if path.suffix.lower() == ".txt":
        return path.read_text(encoding="utf-8", errors="replace")

    raise ValueError(f"Unsupported file type: {path.suffix}")


def index_documents(file_paths):
    """Extract, chunk, and embed uploaded documents."""
    global document_chunks, document_embeddings, document_metadata

    if not file_paths:
        return "Upload at least one PDF or TXT file."

    new_chunks = []
    new_metadata = []

    for file_path in file_paths:
        try:
            text = read_document(file_path)
            chunks = split_into_chunks(text)

            for index, chunk in enumerate(chunks):
                new_chunks.append(chunk)
                new_metadata.append({
                    "source": Path(file_path).name,
                    "chunk": index + 1
                })

        except Exception as error:
            print("Could not process", file_path, ":", error)

    if not new_chunks:
        return "No readable text found. Scanned PDFs may need OCR."

    # Replace the current index with the newly uploaded documents.
    document_chunks = new_chunks
    document_metadata = new_metadata

    document_embeddings = embedder.encode(
        document_chunks,
        convert_to_numpy=True,
        normalize_embeddings=True,
        show_progress_bar=False
    )

    return (
        f"Indexed {len(document_chunks)} chunks from "
        f"{len(set(m['source'] for m in document_metadata))} document(s)."
    )


def retrieve_documents(query, top_k=3):
    """Retrieve semantically similar document chunks."""
    if document_embeddings is None or not document_chunks:
        return []

    query_embedding = embedder.encode(
        [query],
        convert_to_numpy=True,
        normalize_embeddings=True
    )[0]

    scores = document_embeddings @ query_embedding
    best_indices = np.argsort(scores)[::-1][:top_k]

    results = []

    for index in best_indices:
        results.append({
            "text": document_chunks[index],
            "source": document_metadata[index]["source"],
            "chunk": document_metadata[index]["chunk"],
            "score": float(scores[index])
        })

    return results


def answer_from_documents(question):
    """Generate an answer grounded in retrieved document chunks."""
    results = retrieve_documents(question)

    if not results:
        return {
            "answer": "No indexed documents are available. Upload and index a PDF or TXT file first.",
            "sources": []
        }

    context = "\n\n".join(
        f"[Source: {r['source']}, chunk {r['chunk']}]\n{r['text']}"
        for r in results
    )

    prompt = f"""
Answer the question using the supplied document excerpts.

Question:
{question}

Document excerpts:
{context}

Rules:
- Prioritize information in the excerpts.
- If the excerpts do not answer the question, say so.
- Do not invent facts or citations.
- Cite supporting sources using [Source: filename, chunk N].
- Distinguish source facts from your own suggestions.
"""

    result = generate_text(
        prompt,
        system_instruction=(
            "You are a document-grounded assistant. "
            "Do not claim a source supports information it does not contain."
        ),
        max_new_tokens=300
    )

    return {
        "answer": result["text"],
        "sources": [
            {
                "source": r["source"],
                "chunk": r["chunk"],
                "similarity": round(r["score"], 3)
            }
            for r in results
        ]
    }


